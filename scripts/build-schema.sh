#!/usr/bin/env bash
# Builds supabase/schema.sql — a single file that stands up a fresh Supabase project.
#
# Why this exists: supabase/migrations/ has three files without a date prefix
# (init_schema.sql, add_auto_dev.sql, add_kakao_support.sql). Sorted by name they land
# AFTER the dated ones, so `ls | sort` (and `supabase db push`, which also ignores the
# non-14-digit prefixes) replays history in the wrong order and fails on a new database.
# Production applied them in the order below (verified against the original repo's git
# history on 2026-10-18). Judges and new contributors run the generated file instead.
#
# Usage:  scripts/build-schema.sh            # regenerates supabase/schema.sql
#         psql "$POSTGRES_URL_NON_POOLING" -v ON_ERROR_STOP=1 -f supabase/schema.sql
set -euo pipefail
cd "$(dirname "$0")/.."

MIG=supabase/migrations
OUT=supabase/schema.sql

ordered=(init_schema.sql add_auto_dev.sql add_kakao_support.sql)
while IFS= read -r f; do ordered+=("$f"); done < <(ls "$MIG" | grep -E '^[0-9]{8}_' | LC_ALL=C sort)

{
  echo "-- GENERATED by scripts/build-schema.sh — do not edit by hand. Re-run the script after adding a migration."
  echo "-- Stands up a fresh Supabase project in one go. Apply with:"
  echo "--   psql \"\$POSTGRES_URL_NON_POOLING\" -v ON_ERROR_STOP=1 -f supabase/schema.sql"
  echo "-- Requires Supabase (auth.uid(), roles anon/authenticated/service_role, pgrst)."
  echo "-- Files in apply order (${#ordered[@]}):"
  for f in "${ordered[@]}"; do echo "--   $f"; done
  for f in "${ordered[@]}"; do
    printf '\n\n-- ═══════════════════════════ %s ═══════════════════════════\n\n' "$f"
    cat "$MIG/$f"
    # make sure the next file starts on its own line even if this one lacks a trailing newline
    [ -n "$(tail -c1 "$MIG/$f")" ] && echo
  done
} > "$OUT"

echo "wrote $OUT (${#ordered[@]} files, $(wc -l < "$OUT" | tr -d ' ') lines)"
