// 사람이 쓴 문자열을 «한 줄로» 접는 공용 유틸.
//
// 왜 한 곳인가 — 이 레포는 사본이 갈라져 한쪽만 고쳐지는 사고를 반복했다
// (`WIDGET_CHIP_LABELS` 가 appearance 와 위젯 라우트에 두 벌 있어 칩 문구를 고치면
// 미리보기만 옛 문구로 남았다). 이 함수는 지금 두 곳이 쓴다:
//   - 위젯 모양의 시작 질문·인사말 (`lib/bot/appearance.ts`)
//   - 방문자 연락처의 이름 (`api/widget/[botId]/contact`)
// 뒤엣것은 **분류 프롬프트로 흘러가므로** 개행이 남으면 레코드 경계를 흉내 낼 수 있다.

/**
 * 앞뒤를 자르고 내부 공백·개행을 한 칸으로 접는다.
 *
 * `\s` 가 못 잡는 것을 먼저 지운다 — 제로폭(U+200B)·양방향 재정의(U+202E)·제어 문자는
 * 공백이 아니라 그대로 저장되고, 문구를 시각적으로 뒤집어 보이게 할 수 있다.
 * 채널톡 경로에서 서로게이트를 자른 것과 같은 결이다.
 */
export function collapseWhitespace(value: string): string {
  return (
    value
      // 탭·개행(\u0009~\u000D)과 U+2028/2029 는 «빼고» 지운다 — 그건 아래 \s 가
      // 공백으로 접어야 한다. 여기서 같이 지우면 줄이 바뀐 자리에서 단어가 붙는다.
      .replace(
        /[\u0000-\u0008\u000E-\u001F\u007F-\u009F\u200B-\u200F\u202A-\u202E\u2066-\u2069\uFEFF]/g,
        '',
      )
      .replace(/\s+/g, ' ')
      .trim()
  );
}
