import { SectionHead } from './SectionHead';
import { GuidedDemo } from '@/components/demo/guided/GuidedDemo';

/**
 * 「데모」 섹션 — 가이드 딸린 데모 무대를 통째로 페이지에 싣는다.
 *
 * 2026-09-18 ny 결정 네 단계를 거쳐 여기까지 왔다.
 *  ① 「클릭하지 않고도 볼 수 있게 아예 임베딩」 → 널널투어 iframe 을 상시 띄웠다.
 *  ② 「이게 데모인지도 모르겠고 갑자기 다른 톤의 서비스가 등장하는 느낌」 → 독립 섹션으로 올려
 *     `SectionHead`(배지·40px 제목·리드)를 다른 섹션과 같은 위상으로 두고, 회색 판 위에 띄웠다.
 *  ③ 「가이드와 함께 보기 버튼이 따로 있는 게 아니고 그 가이드 섹션 자체를 임베딩」
 *     → 버튼을 없애고 무대를 `inline` 으로 그대로 싣는다. 내려오면 왼쪽 튜토리얼과
 *       오른쪽 실화면이 «이미» 떠 있다.
 *  ④ 「우리가 방금 계속 만들었던 데모를 랜딩에 넣고 싶은거야」(2026-09-18 밤)
 *     → 무대를 `GuidedDemo`(각본 11단계)로 갈아 끼웠다. 예전 무대는 널널투어 실서비스를
 *       iframe 으로 띄우고 실제 API 를 폴링했다 — 심사 기간에 남의 서비스가 흔들리면 같이 흔들린다.
 *       지금 무대는 **전부 우리 주소의 사본**이라 서버로 나가는 요청이 0 이다.
 *  ⑤ 「차라리 데모 섹션을 히어로처럼 아예 좌우 여백 패딩 없이 전체 다 색칠하는 식이면」(밤 5차)
 *     → 아래 「왜 띠인가」.
 *
 * ⚠️ 무대 본체는 `GuidedDemo` 하나이고, 이 섹션이 유일한 사용처다. 팝업 진입점
 *    (`LiveDemoButton`)은 ③ 이후 랜딩 어디서도 쓰지 않는다 — 지우지 않고 둔 건 팝업 모드가
 *    여전히 동작하고, 되돌릴 때 진입점만 다시 꽂으면 되기 때문이다.
 *
 * ⚠️ `id="try"` 는 히어로·나브의 「데모」가 내려오는 자리다(`DemoAnchor`). 바꾸면 둘 다 끊긴다.
 *    `.landing section[id]` 에 `scroll-margin-top` 이 걸려 있어 따로 줄 필요는 없다.
 *
 * ── 왜 «띠» 인가 ──────────────────────────────────────────────
 * 전에는 연분홍 «카드»(1200px 안, 코랄 1px 테두리)가 흰 지면 위에 놓여 있었다. 카드는 「이 페이지의
 * 한 부품」으로 읽힌다. 히어로만 지면을 통째로 칠하고 있어서, 랜딩에서 «장이 바뀌는 자리»는
 * 히어로 하나뿐이었다. 데모는 이 페이지에서 유일하게 **손으로 만져 보는 곳**이라 같은 위상이 맞다.
 * 그래서 색을 카드에서 지면으로 옮겼다 — 띠는 화면 폭 전체를 채우고, 무대만 가운데 1200px 에 선다.
 *
 * 🔴 **띠를 진한 코랄로 칠하지 않는다.** 무대 «안»에서 코랄은 「지금 여기를 누르세요」 신호다
 *    (깜빡이는 링·말풍선·단계 번호). 지면까지 같은 채도면 그 신호가 지면에 묻힌다 — 22:05 에
 *    테두리를 정할 때 이미 겪은 것이고, 면적이 넓어진 지금은 더 크게 묻힌다.
 *    그래서 **가장 연한 단계**(`--coral-tint-2`)로 넓게 깐다. 히어로는 진한 코랄 + 흰 글자,
 *    여기는 연한 코랄 + 검은 글자 — 같은 「장」이되 서로 경쟁하지 않는다.
 *
 * ⚠️ `SectionHead` 의 배지는 `--coral-tint`(더 연함)다. 띠를 `--coral-tint` 로 깔면 배지가
 *    지면에 녹아 사라진다. 한 단계 진한 `--coral-tint-2` 라야 배지가 살아 있다.
 *
 * ⚠️ 띠 «안»의 흰 무대에는 테두리를 두르지 않는다. 연분홍 위의 흰 판은 그 자체로 경계가 서고,
 *    `GuidedDemo` 가 이미 자기 그림자(`0 10px 28px`)를 갖고 있다.
 */
export function DemoSection() {
  return (
    <section
      id="try"
      className="bg-[var(--coral-tint-2)]"
      // 위 여백은 띠 «밖»(흰 지면과 떨어뜨린다), 아래 여백은 띠 «안»(다음 섹션은 자기 여백을 갖는다).
      style={{
        marginTop: 'var(--space-section)',
        paddingTop: 'var(--space-section)',
        paddingBottom: 'var(--space-section)',
      }}
    >
      <div className="mx-auto max-w-[1200px] px-6">
        <SectionHead
          kicker="데모"
          title="피드루프를 경험하세요"
          lead={
            <>
              피드루프 챗봇에게 말을 걸어보세요.
              <br />
              AI 분류부터 수정안, 반영 알림까지 한 바퀴를 그대로 겪어볼 수 있습니다.
            </>
          }
        />

        <div className="mt-8 lg:mt-10">
          <GuidedDemo inline />
        </div>
      </div>
    </section>
  );
}
