-- 시작 질문을 「띄우지 않기」로 둘 수 있게 한다.
--
-- 20260911_01 로 첫 화면에 「자주 묻는 질문」 칩이 생기면서, 운영자가 시작 질문을
-- 비워두면 답변 지식 FAQ 앞 3개가 자동으로 방문자에게 보이게 됐다. 편리하지만
-- «끄는 방법이 없었다» — 빈 배열이 곧 「FAQ 로 채워라」라는 뜻이라, 아무것도 안
-- 띄우겠다는 의사를 표현할 자리가 없었다.
--
-- FAQ 질문 문장 자체가 비밀인 경우는 드물지만, 운영자가 내부용 문답을 지식에 넣으면
-- 그 질문이 아무 조작 없이 공개 위젯 첫 화면에 뜬다. 동의한 적 없는 공개다.
--
-- 기본값 true 는 지금 동작 그대로다(설계 결정: 운영자 지정 → 없으면 FAQ 폴백).
-- 기존 봇은 한 곳도 바뀌지 않고, 끄고 싶은 운영자만 위젯 모양 화면에서 끈다.
--
-- 이 컬럼은 «칸이 비었을 때»만 본다. 시작 질문을 직접 써 넣으면 그게 언제나 이긴다.
ALTER TABLE bots ADD COLUMN IF NOT EXISTS starter_faq_fallback BOOLEAN NOT NULL DEFAULT true;

COMMENT ON COLUMN bots.starter_faq_fallback IS '시작 질문(starter_questions)이 비었을 때 knowledge_faq 앞쪽 질문으로 채울지. false 면 위젯 첫 화면에 「자주 묻는 질문」 줄이 뜨지 않는다. 직접 쓴 시작 질문이 있으면 이 값과 무관하게 그게 뜬다.';
